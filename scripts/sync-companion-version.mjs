#!/usr/bin/env node
// Run after the release's root version bump. CI and publishing check without
// --write, so neither an omitted bump nor an accidentally widened peer can ship.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const { version } = read('package.json');
const legacyPath = new URL('packages/legacy-office/package.json', root);
const legacy = read('packages/legacy-office/package.json');
const versionPath = new URL('src/companion-version.ts', root);
const source = `// Generated by pnpm sync:versions; checked in CI and before publishing.\nexport const COMPANION_VERSION = '${version}';\n`;
if (process.argv.includes('--write')) {
  legacy.version = version;
  legacy.peerDependencies['@silurus/ooxml'] = version;
  writeFileSync(legacyPath, JSON.stringify(legacy, null, 2) + '\n');
  writeFileSync(versionPath, source);
} else {
  if (legacy.version !== version || legacy.peerDependencies['@silurus/ooxml'] !== version
      || readFileSync(versionPath, 'utf8') !== source) {
    throw new Error('Companion version/peer/runtime pin differs from root; run pnpm sync:versions');
  }
}
console.log(`Companion lockstep verified: ${version}`);
